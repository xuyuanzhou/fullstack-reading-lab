const sectionByKey = new Map(AI_NOTE_INDEX.map(([key, section]) => [key, section]))

/** 进度 id 形如 ai:课键。不在目录里就没有这一节。 */
export function aiNoteRef(progressId: string): { key: string; section: string } | undefined {
  if (!progressId.startsWith('ai:')) return undefined
  const key = progressId.slice(3)
  const section = sectionByKey.get(key)
  if (!section) return undefined
  return { key, section }
}
