type RoadRow = { questionId: string; correct: boolean; mode: 'gate' | 'retry'; attempt: number; at: number }

function rowsFor(log: readonly RoadRow[], ids: readonly string[], mode: RoadRow['mode']) {
  const known = new Set(ids)
  return log.filter((row) => row.mode === mode && known.has(row.questionId))
}

function byAttempt(rows: readonly RoadRow[]) {
  const map = new Map<number, RoadRow[]>()
  for (const row of rows) {
    const list = map.get(row.attempt) ?? []
    list.push(row)
    map.set(row.attempt, list)
  }
  return [...map.entries()].sort((left, right) => left[0] - right[0])
}

function covers(rows: readonly RoadRow[], ids: readonly string[]) {
  if (!ids.length) return false
  const have = new Set(rows.map((row) => row.questionId))
  return ids.every((id) => have.has(id))
}

function correctCount(rows: readonly RoadRow[], ids: readonly string[]) {
  const byId = new Map(rows.map((row) => [row.questionId, row]))
  return ids.reduce((sum, id) => sum + (byId.get(id)?.correct ? 1 : 0), 0)
}

function wrongIds(rows: readonly RoadRow[], ids: readonly string[]) {
  const byId = new Map(rows.map((row) => [row.questionId, row]))
  return ids.filter((id) => byId.get(id)?.correct === false)
}

function gateFace(log: readonly RoadRow[], ids: readonly string[]) {
  const pairs = byAttempt(rowsFor(log, ids, 'gate'))
  const completed = pairs.filter(([, rows]) => covers(rows, ids))
  const cleared = completed.some(([, rows]) => rows.length > 0 && correctCount(rows, ids) * 100 >= ids.length * 80)
  const completeNumbers = completed.map(([attempt]) => attempt)
  const highestComplete = completeNumbers.length ? Math.max(...completeNumbers) : 0
  const openGate = [...pairs].reverse().find(([attempt, rows]) => attempt > highestComplete && !covers(rows, ids))
  const last = completed.at(-1)?.[1]
  const missed = last ? wrongIds(last, ids) : []
  const lastEnd = last ? last.reduce((max, row) => Math.max(max, row.at), 0) : 0
  const openRetry = last && missed.length
    ? [...byAttempt(rowsFor(log, ids, 'retry'))].reverse().find(([, rows]) => Math.min(...rows.map((row) => row.at)) > lastEnd && !covers(rows, missed))
    : undefined
  return { cleared, open: Boolean(openGate || openRetry) }
}

export type DrillRoadFace = {
  id: string
  title: string
  status: 'open' | 'live' | 'cleared'
  state: string
  cleared: number
  total: number
}

/** 和选择题大厅同一套词：可以开始、进行中、第 n 关、已通过。 */
export function drillRoadFaces(log: readonly RoadRow[]): DrillRoadFace[] {
  return DRILL_ROADS.map((course) => {
    const plays = course.gates.map((gate) => gateFace(log, gate.questionIds))
    const cleared = plays.filter((play) => play.cleared).length
    const here = plays.findIndex((play) => !play.cleared)
    const started = here >= 0 && plays[here].open
    const status = cleared === course.gates.length ? 'cleared' : cleared > 0 || started ? 'live' : 'open'
    const state = status === 'cleared' ? '已通过' : started ? '进行中' : cleared > 0 ? `第 ${here + 1} 关` : '可以开始'
    return { id: course.id, title: course.title, status, state, cleared, total: course.gates.length }
  })
}
